// Regenerates the three registries from the file system so parallel authors never edit them by hand:
//   packages/spec/src/specs/index.ts   (every *.spec.ts)
//   packages/react/src/fixtures.ts     (every components/<id>/<id>.fixture.tsx)
//   packages/react/src/index.ts        (public exports, from each component's index.ts)
// Usage: pnpm registry
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { componentsDir, reactSrc, specsDir } from './paths.ts';

const camel = (id: string) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase()).replace(/^(switch|default|delete|new|class)$/, '$1_');
const write = (path: string, content: string) => { if (!existsSync(path) || readFileSync(path, 'utf8') !== content) writeFileSync(path, content); };

const specIds = readdirSync(specsDir).filter(f => f.endsWith('.spec.ts')).map(f => f.replace('.spec.ts', '')).sort();
write(join(specsDir, 'index.ts'), `// Generated by \`pnpm registry\`. Do not edit.
import type { SpecInput } from '../schema.ts';
${specIds.map(id => `import ${camel(id)} from './${id}.spec.ts';`).join('\n')}

export const registry: Record<string, SpecInput> = {
${specIds.map(id => `  '${id}': ${camel(id)},`).join('\n')}
};
`);

const comps = readdirSync(componentsDir, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort();
const withFixture = comps.filter(id => existsSync(join(componentsDir, id, `${id}.fixture.tsx`)));
write(join(reactSrc, 'fixtures.ts'), `// Generated by \`pnpm registry\`. Do not edit.
import type { Fixture } from './lib/fixture.ts';
${withFixture.map(id => `import ${camel(id)} from './components/${id}/${id}.fixture.tsx';`).join('\n')}

export const fixtures: Record<string, Fixture> = {
${withFixture.map(id => `  '${id}': ${camel(id)},`).join('\n')}
};
`);

const withIndex = comps.filter(id => existsSync(join(componentsDir, id, 'index.ts')));
write(join(reactSrc, 'index.ts'), `// Generated by \`pnpm registry\`. Do not edit. Each component's public API lives in components/<id>/index.ts.
export { cn } from './lib/cn.ts';
export { useControllableState } from './hooks/use-controllable-state.ts';
export { useScrub, scrubValue } from './hooks/use-scrub.ts';

${withIndex.map(id => `export * from './components/${id}/index.ts';`).join('\n')}
`);
console.log(`registry: ${specIds.length} specs, ${withFixture.length} fixtures, ${withIndex.length} component modules`);
